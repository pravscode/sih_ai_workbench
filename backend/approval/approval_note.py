from pathlib import Path
from datetime import datetime

from docx import Document


OUTPUT_DIR = Path("outputs")
OUTPUT_DIR.mkdir(parents=True, exist_ok=True)


def generate_approval_note(reasoning_result):
    """
    Generate a Word approval/review note from
    evidence-grounded inspection reasoning.
    """

    inspection = reasoning_result.get(
        "inspection_evidence",
        {}
    )

    finding_summary = reasoning_result.get(
        "finding_summary",
        "Not available"
    )

    sop_match = reasoning_result.get(
        "sop_match",
        "Not available"
    )

    reasoning = reasoning_result.get(
        "reasoning",
        "Not available"
    )

    recommended_action = reasoning_result.get(
        "recommended_action"
    )

    support_status = reasoning_result.get(
        "support_status",
        "NOT_SUPPORTED"
    )

    citations = reasoning_result.get(
        "evidence_citations",
        []
    )

    document = Document()

    # Title
    title = document.add_heading(
        "INDUSTRIAL INSPECTION REVIEW",
        level=0
    )

    document.add_paragraph(
        "Generated by Sovereign AI Workbench"
    )

    # Basic inspection information
    document.add_heading(
        "Inspection Information",
        level=1
    )

    table = document.add_table(
        rows=0,
        cols=2
    )

    inspection_fields = [
        ("Equipment ID", inspection.get("equipment_id")),
        ("Equipment Type", inspection.get("equipment_type")),
        ("Inspection Date", inspection.get("inspection_date")),
        ("Location", inspection.get("location")),
        ("Severity", inspection.get("severity")),
    ]

    for label, value in inspection_fields:
        row = table.add_row().cells
        row[0].text = label
        row[1].text = str(value) if value else "Not specified"

    # Finding
    document.add_heading(
        "Inspection Finding",
        level=1
    )

    document.add_paragraph(
        finding_summary
    )

    # SOP assessment
    document.add_heading(
        "SOP Assessment",
        level=1
    )

    document.add_paragraph(
        f"Match status: {sop_match}"
    )

    document.add_paragraph(
        reasoning
    )

    # Recommended action
    document.add_heading(
        "Recommended Action",
        level=1
    )

    if recommended_action:
        document.add_paragraph(
            recommended_action
        )
    else:
        document.add_paragraph(
            "No specific action is supported by "
            "the retrieved SOP/manual evidence."
        )

    # Support status
    document.add_heading(
        "Evidence Support Status",
        level=1
    )

    document.add_paragraph(
        support_status
    )

    # Citations
    document.add_heading(
        "Evidence Citations",
        level=1
    )

    if citations:
        for citation in citations:

            if isinstance(citation, dict):
                source = citation.get(
                    "source",
                    "Unknown"
                )
                page = citation.get(
                    "page",
                    "Unknown"
                )

                document.add_paragraph(
                    f"{source} — Page {page}",
                    style="List Bullet"
                )

            elif isinstance(citation, list):
                source = (
                    citation[0]
                    if len(citation) > 0
                    else "Unknown"
                )

                page = (
                    citation[1]
                    if len(citation) > 1
                    else "Unknown"
                )

                document.add_paragraph(
                    f"{source} — Page {page}",
                    style="List Bullet"
                )

    else:
        document.add_paragraph(
            "No supporting citations were returned."
        )

    # Generation metadata
    document.add_heading(
        "Generation Information",
        level=1
    )

    document.add_paragraph(
        f"Generated locally: "
        f"{datetime.now().strftime('%Y-%m-%d %H:%M:%S')}"
    )

    document.add_paragraph(
        "Processing mode: Local / On-Premise"
    )

    # Save
    equipment_id = inspection.get(
        "equipment_id",
        "inspection"
    )

    safe_equipment_id = str(
        equipment_id
    ).replace("/", "_").replace("\\", "_")

    output_path = (
        OUTPUT_DIR /
        f"approval_note_{safe_equipment_id}.docx"
    )

    document.save(output_path)

    print(
        "APPROVAL NOTE CREATED:",
        output_path
    )

    return str(output_path)